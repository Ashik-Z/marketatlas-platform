CREATE TABLE asset_identifier (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  asset_id BIGINT NOT NULL,
                                  scheme VARCHAR(50) NOT NULL,
                                  identifier_value VARCHAR(255) NOT NULL,
                                  CONSTRAINT fk_asset_identifier_asset
                                      FOREIGN KEY (asset_id) REFERENCES asset(id),
                                  CONSTRAINT asset_identifier_scheme_check
                                      CHECK (scheme IN ('TWELVE_DATA_SYMBOL')),
                                  CONSTRAINT uk_asset_identifier_scheme_value
                                      UNIQUE (scheme, identifier_value),
                                  CONSTRAINT uk_asset_identifier_asset_scheme
                                      UNIQUE (asset_id, scheme)
);

INSERT INTO asset_identifier (asset_id, scheme, identifier_value)
SELECT id, 'TWELVE_DATA_SYMBOL', symbol
FROM asset
WHERE symbol IS NOT NULL;

ALTER TABLE asset DROP COLUMN symbol;