CREATE TABLE account (
     id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     name             VARCHAR(100)   NOT NULL,
     currency         VARCHAR(3)     NOT NULL,
     starting_balance NUMERIC(20, 6) NOT NULL,
     cash_balance     NUMERIC(20, 6) NOT NULL,
     created_at       TIMESTAMPTZ    NOT NULL,
     CONSTRAINT account_currency_format CHECK (currency ~ '^[A-Z]{3}$'),
     CONSTRAINT account_starting_balance_non_negative CHECK (starting_balance >= 0),
     CONSTRAINT account_cash_balance_non_negative CHECK (cash_balance >= 0)
);