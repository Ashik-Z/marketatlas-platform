CREATE TABLE trade (
                       id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       account_id  BIGINT         NOT NULL REFERENCES account (id),
                       asset_id    BIGINT         NOT NULL REFERENCES asset (id),
                       side        VARCHAR(4)     NOT NULL,
                       quantity    NUMERIC(20, 6) NOT NULL,
                       price       NUMERIC(20, 6) NOT NULL,
                       commission  NUMERIC(20, 6) NOT NULL,
                       price_date  DATE           NOT NULL,
                       executed_at TIMESTAMPTZ    NOT NULL,
                       CONSTRAINT trade_side CHECK (side IN ('BUY', 'SELL')),
                       CONSTRAINT trade_quantity_positive CHECK (quantity > 0),
                       CONSTRAINT trade_price_positive CHECK (price > 0),
                       CONSTRAINT trade_commission_non_negative CHECK (commission >= 0)
);

CREATE INDEX idx_trade_account_asset ON trade (account_id, asset_id);