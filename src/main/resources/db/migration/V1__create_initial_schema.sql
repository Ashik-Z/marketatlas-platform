
CREATE TABLE issuer (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        country VARCHAR(255),
                        name VARCHAR(255)
);

CREATE TABLE asset (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       asset_class VARCHAR(255) NOT NULL,
                       name VARCHAR(255) NOT NULL,
                       symbol VARCHAR(255),
                       issuer_id BIGINT,
                       CONSTRAINT asset_asset_class_check
                           CHECK (asset_class IN ('EQUITY', 'COMMODITY')),
                       CONSTRAINT fk_asset_issuer
                           FOREIGN KEY (issuer_id) REFERENCES issuer(id)
);

CREATE TABLE market_data (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             close DOUBLE PRECISION,
                             high DOUBLE PRECISION,
                             low DOUBLE PRECISION,
                             open DOUBLE PRECISION,
                             timestamp DATE NOT NULL,
                             volume DOUBLE PRECISION,
                             asset_id BIGINT NOT NULL,
                             CONSTRAINT uk_market_data_asset_timestamp
                                 UNIQUE (asset_id, timestamp),
                             CONSTRAINT fk_market_data_asset
                                 FOREIGN KEY (asset_id) REFERENCES asset(id)
);
