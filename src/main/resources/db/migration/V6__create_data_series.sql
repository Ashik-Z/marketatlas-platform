-- Single-value time series (inflation indices, energy prices) from non-OHLC providers.
-- Kept separate from market_data, which holds open/high/low/close/volume bars.
CREATE TABLE data_series (
                             id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             provider            varchar(30)  NOT NULL,
                             external_id         varchar(100) NOT NULL,
                             name                varchar(255) NOT NULL,
                             frequency           varchar(20)  NOT NULL,
                             units               varchar(100) NOT NULL,
                             source_organization varchar(100) NOT NULL,
                             copyright_class     varchar(50)  NOT NULL,
                             attribution         varchar(500) NOT NULL,
                             CONSTRAINT uk_data_series_provider_external UNIQUE (provider, external_id)
);

-- value is NULL when the provider reports the date as missing; it is never stored as zero.
CREATE TABLE series_observation (
                                    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    series_id        bigint        NOT NULL REFERENCES data_series (id),
                                    observation_date date          NOT NULL,
                                    value            numeric(20, 6),
                                    fetched_at       timestamptz   NOT NULL,
                                    CONSTRAINT uk_series_observation_series_date UNIQUE (series_id, observation_date)
);