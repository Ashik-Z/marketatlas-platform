CREATE TABLE market_data_coverage (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      asset_id BIGINT NOT NULL,
                                      start_date DATE NOT NULL,
                                      end_date DATE NOT NULL,
                                      fetched_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
                                      CONSTRAINT fk_market_data_coverage_asset
                                          FOREIGN KEY (asset_id) REFERENCES asset(id),
                                      CONSTRAINT market_data_coverage_range_check
                                          CHECK (start_date <= end_date)
);

CREATE INDEX idx_market_data_coverage_asset_range
    ON market_data_coverage (asset_id, start_date, end_date);